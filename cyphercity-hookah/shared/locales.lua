function L(key, ...)
    local lang = Locales[Config.Locale] or Locales.he
    local template = lang[key] or Locales.he[key] or key
    if select('#', ...) > 0 then
        local ok, result = pcall(string.format, template, ...)
        if ok then return result end
    end
    return template
end
