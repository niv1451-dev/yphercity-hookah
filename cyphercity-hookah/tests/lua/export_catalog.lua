-- Exports the real catalog/config (from config.lua) as sample data for the
-- browser preview of the NUI: lua5.4 tests/lua/export_catalog.lua > tests/nui/mock-data.js

local here = debug.getinfo(1, 'S').source:sub(2):match('(.*)/lua/export_catalog%.lua$') or 'tests'
TEST_ROOT = here
RESOURCE_ROOT = here .. '/..'
dofile(TEST_ROOT .. '/lua/mock_fivem.lua')
MOCK.Reset(false)
for _, file in ipairs({ 'config.lua', 'shared/utils.lua', 'shared/locales.lua', 'shared/items.lua' }) do
    dofile(RESOURCE_ROOT .. '/' .. file)
end

local tables = {}
for _, def in ipairs(Config.Tables) do
    local seats = {}
    for i = 1, #def.seats do seats[i] = false end
    tables[#tables + 1] = {
        id = def.id, label = def.label, capacity = def.capacity, vip = def.vip == true,
        status = 'free', members = 0, seated = 0, occupiedSeats = seats,
    }
end

local accounts = {}
for _, account in ipairs(Config.Payments.accounts) do
    accounts[#accounts + 1] = { id = account, label = L('account_' .. account) }
end

local data = {
    locale = Config.Locale,
    currency = Config.Currency,
    business = { name = Config.Business.name, label = Config.Business.label, hostess = Config.Hostess.name },
    catalog = Catalog.ForNui(),
    tables = tables,
    settings = {
        framework = 'qbcore',
        moneyMode = 'money',
        timing = Config.Payments.timing,
        accounts = accounts,
        tips = Config.Payments.tips.enabled and Config.Payments.tips.options or { 0 },
        servicePercent = Config.Payments.serviceChargePercent,
        allowTableBill = Config.Payments.allowTableBill,
        tableBillPayer = Config.Payments.tableBillPayer,
        maxPartySize = Config.TableSettings.maxPartySize,
        allowWithoutTable = Config.Orders.allowWithoutTable == true,
        maxQtyPerLine = Config.Orders.maxQtyPerLine,
        maxItemsPerOrder = Config.Orders.maxItemsPerOrder,
        ordersMode = Config.Orders.mode,
        flavorChange = Config.Hookah.flavorChange,
        coalRefresh = Config.Hookah.coalRefresh,
        stockEnabled = Config.Stock.enabled,
    },
    messages = {
        order_placed = L('order_placed', '%ID%', '%TOTAL%'),
        payment_success = L('payment_success', '%TOTAL%'),
        table_assigned = L('table_assigned', '%TABLE%', '3:00'),
        insufficient_funds = L('insufficient_funds', L('account_cash')),
    },
}

io.write('// Generated by tests/lua/export_catalog.lua from config.lua — sample data for the browser preview.\n')
io.write('window.CCH_MOCK_DATA = ' .. json.encode(data) .. ';\n')
